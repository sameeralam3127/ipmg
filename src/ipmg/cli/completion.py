"""Shell completion scripts, generated from the argparse definitions (``ipmg completion``).

Every command's parser is read when the script is generated, so a new flag
completes without anyone touching this file. The scripts themselves are
static: pressing TAB never starts Python.
"""

from __future__ import annotations

import argparse
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field

SHELLS = ("bash", "zsh", "fish", "powershell")

#: Flags whose values are paths, by argparse dest: they complete file names.
_FILE_DESTS = frozenset({"input", "config", "db", "resume", "output", "diff_output"})


@dataclass(frozen=True)
class Flag:
    names: tuple[str, ...]
    help: str
    #: Whether the flag takes a value at all.
    takes_value: bool
    choices: tuple[str, ...] = ()
    files: bool = False
    #: Takes several values after one flag (nargs "+" or "*").
    multiple: bool = False

    @property
    def long(self) -> str:
        return next((name for name in self.names if name.startswith("--")), self.names[0])


@dataclass(frozen=True)
class Command:
    #: "" for the scan command (plain ``ipmg``); "history prune" for a nested one.
    name: str
    help: str
    flags: tuple[Flag, ...]
    #: Words that may follow the command, such as shells or "prune".
    positionals: tuple[str, ...] = field(default_factory=tuple)


def _flags(parser: argparse.ArgumentParser) -> tuple[Flag, ...]:
    flags = []
    for action in parser._actions:  # argparse's only route to its flags
        if not action.option_strings or action.help == argparse.SUPPRESS:
            continue
        takes_value = action.nargs != 0
        flags.append(
            Flag(
                names=tuple(action.option_strings),
                help=" ".join((action.help or "").split()).replace("%%", "%"),
                takes_value=takes_value,
                choices=tuple(str(choice) for choice in action.choices or ()),
                files=takes_value and action.dest in _FILE_DESTS,
                multiple=action.nargs in ("+", "*"),
            )
        )
    return tuple(flags)


def commands() -> list[Command]:
    """Every command IPMG has, read from its parsers."""
    # Imported here: parser imports this module's caller, not the other way round.
    from ipmg.cli import parser as p

    def first_line(build: Callable[[], argparse.ArgumentParser]) -> str:
        text = build().description or ""
        return text.split(". ")[0].rstrip(".")

    subcommands: Sequence[tuple[str, Callable[[], argparse.ArgumentParser], tuple[str, ...]]] = (
        ("web", p.build_web_parser, ()),
        ("history", p.build_history_parser, ("prune",)),
        ("history prune", p.build_prune_parser, ()),
        ("diff", p.build_diff_parser, ()),
        ("compare", p.build_diff_parser, ()),
        ("wake", p.build_wake_parser, ()),
        ("completion", p.build_completion_parser, SHELLS),
    )
    found = [Command("", "Scan targets and save a report", _flags(p.build_parser()))]
    for name, build, positionals in subcommands:
        found.append(Command(name, first_line(build), _flags(build()), positionals))
    return found


def _subcommand_names(found: Sequence[Command]) -> list[str]:
    return [command.name for command in found if command.name and " " not in command.name]


# ---------------------------------------------------------------------- bash


def _bash_case_value(flag: Flag) -> str:
    if flag.choices:
        return "choice " + " ".join(flag.choices)
    if flag.files:
        return "file"
    return "value" if flag.takes_value else ""


def bash_script(found: Sequence[Command]) -> str:
    """Works in bash 3.2 (macOS) and later; needs no bash-completion package."""
    names = " ".join(_subcommand_names(found))
    flag_cases, value_cases, multi_cases, positional_cases = [], [], [], []
    for command in found:
        words = " ".join(name for flag in command.flags for name in flag.names)
        flag_cases.append(f'        "{command.name}") echo "{words}" ;;')
        for flag in command.flags:
            kind = _bash_case_value(flag)
            if kind:
                keys = "|".join(f'"{command.name}|{name}"' for name in flag.names)
                value_cases.append(f'        {keys}) echo "{kind}" ;;')
            if flag.multiple:
                keys = "|".join(f'"{command.name}|{name}"' for name in flag.names)
                multi_cases.append(f"        {keys}) return 0 ;;")
        if command.positionals:
            positional_cases.append(
                f'        "{command.name}") echo "{" ".join(command.positionals)}" ;;'
            )

    return f"""# ipmg completion for bash, generated by `ipmg completion bash`.
# Load it from ~/.bashrc:  eval "$(ipmg completion bash)"

_ipmg_flags() {{
    case "$1" in
{chr(10).join(flag_cases)}
    esac
}}

_ipmg_value() {{
    case "$1|$2" in
{chr(10).join(value_cases)}
    esac
}}

_ipmg_multi() {{
    case "$1|$2" in
{chr(10).join(multi_cases)}
    esac
    return 1
}}

_ipmg_positionals() {{
    case "$1" in
{chr(10).join(positional_cases)}
    esac
}}

_ipmg() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="" cmd="" flag="" kind="" word="" i
    COMPREPLY=()
    [ "$COMP_CWORD" -gt 0 ] && prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    if [ "$COMP_CWORD" -gt 1 ]; then
        case " {names} " in
            *" ${{COMP_WORDS[1]}} "*) cmd="${{COMP_WORDS[1]}}" ;;
        esac
    fi
    if [ "$cmd" = "history" ] && [ "$COMP_CWORD" -gt 2 ] && [ "${{COMP_WORDS[2]}}" = "prune" ]; then
        cmd="history prune"
    fi

    # The flag whose value is being typed: the word before, or the last flag
    # if that one takes several values (--input a.txt b.txt <TAB>).
    case "$prev" in
        -*) flag="$prev" ;;
        *)
            i=$((COMP_CWORD - 1))
            while [ "$i" -gt 0 ]; do
                word="${{COMP_WORDS[i]}}"
                case "$word" in
                    -*) _ipmg_multi "$cmd" "$word" && flag="$word"; break ;;
                esac
                i=$((i - 1))
            done
            ;;
    esac

    if [ -n "$flag" ]; then
        case "$cur" in
            -*) ;;
            *)
                kind="$(_ipmg_value "$cmd" "$flag")"
                case "$kind" in
                    choice\\ *)
                        COMPREPLY=( $(compgen -W "${{kind#choice }}" -- "$cur") )
                        return 0
                        ;;
                    file|value)
                        # Nothing offered: readline completes file names.
                        return 0
                        ;;
                esac
                ;;
        esac
    fi

    case "$cur" in
        -*)
            COMPREPLY=( $(compgen -W "$(_ipmg_flags "$cmd")" -- "$cur") )
            return 0
            ;;
    esac
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=( $(compgen -W "{names}" -- "$cur") )
        return 0
    fi
    COMPREPLY=( $(compgen -W "$(_ipmg_positionals "$cmd")" -- "$cur") )
    return 0
}}

complete -o default -F _ipmg ipmg
"""


# ----------------------------------------------------------------------- zsh


def _zsh_quote(text: str) -> str:
    """For inside single quotes, where a backslash is already literal."""
    return text.replace("'", "'\\''")


def _zsh_help(text: str) -> str:
    return text.replace("[", "\\[").replace("]", "\\]").replace(":", "\\:")


def _zsh_spec(flag: Flag) -> str:
    help_text = _zsh_help(flag.help)
    names = flag.names
    if not flag.takes_value:
        argument = ""
    elif flag.choices:
        argument = f":value:({' '.join(flag.choices)})"
    elif flag.files:
        argument = ":path:_files"
    else:
        argument = ":value: "
    equals = "=" if flag.takes_value else ""
    # Repeatable flags (several values, or extend) may appear more than once.
    star = "*" if flag.multiple else ""
    if len(names) == 1:
        return f"'{star}{names[0]}{equals}[{_zsh_quote(help_text)}]{_zsh_quote(argument)}'"
    exclusive = f"({' '.join(names)})"
    return f"'{exclusive}'{{{','.join(names)}}}'{equals}[{_zsh_quote(help_text)}]{_zsh_quote(argument)}'"


def zsh_script(found: Sequence[Command]) -> str:
    """Works sourced, eval'd, or installed on $fpath as ``_ipmg``."""
    by_name: dict[str, Command] = {command.name: command for command in found}
    descriptions = " ".join(
        f"'{name}:{_zsh_quote(_zsh_help(by_name[name].help))}'" for name in _subcommand_names(found)
    )

    continuation = " \\\n                "

    def arguments(command: Command, *extra: str) -> str:
        specs = [_zsh_spec(flag) for flag in command.flags] + list(extra)
        return "_arguments -s" + continuation + continuation.join(specs)

    cases = []
    for command in found:
        if not command.name or " " in command.name:
            continue
        if command.name == "history":
            prune = arguments(by_name["history prune"])
            listing = arguments(command, "'1:subcommand:(prune)'")
            body = (
                "if (( CURRENT > 2 )) && [[ $words[2] == prune ]]; then\n"
                "                shift words; (( CURRENT-- ))\n"
                f"                {prune}\n"
                "            else\n"
                f"                {listing}\n"
                "            fi"
            )
        elif command.positionals:
            shells = " ".join(command.positionals)
            body = arguments(command, f"'1:shell:({shells})'")
        else:
            body = arguments(command)
        cases.append(
            f"        {command.name})\n            shift words; (( CURRENT-- ))\n            {body}\n            ;;"
        )

    return f"""#compdef ipmg
# ipmg completion for zsh, generated by `ipmg completion zsh`.
# Load it from ~/.zshrc, after compinit:  eval "$(ipmg completion zsh)"

_ipmg() {{
    local -a subcommands
    subcommands=({descriptions})
    if (( CURRENT == 2 )) && [[ $words[2] != -* ]]; then
        _describe -t commands 'ipmg command' subcommands
    fi
    case $words[2] in
{chr(10).join(cases)}
        *)
            {arguments(by_name[''])}
            ;;
    esac
}}

if [[ $funcstack[1] == _ipmg ]]; then
    _ipmg "$@"
else
    compdef _ipmg ipmg
fi
"""


# ---------------------------------------------------------------------- fish


def _fish_quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _fish_condition(command: Command, names: Sequence[str]) -> str:
    """When fish should offer a command's flags."""
    if not command.name:
        return f"not __fish_seen_subcommand_from {' '.join(names)}"
    if command.name == "history":
        return "__fish_seen_subcommand_from history; and not __fish_seen_subcommand_from prune"
    if command.name == "history prune":
        return "__fish_seen_subcommand_from history; and __fish_seen_subcommand_from prune"
    return f"__fish_seen_subcommand_from {command.name}"


def _fish_flag(flag: Flag, condition: str) -> str:
    parts = [f"complete -c ipmg -n {_fish_quote(condition)}"]
    for name in flag.names:
        parts.append(f"-l {name[2:]}" if name.startswith("--") else f"-s {name[1:]}")
    if flag.choices:
        parts.append(f"-x -a {_fish_quote(' '.join(flag.choices))}")
    elif flag.files:
        parts.append("-r -F")
    elif flag.takes_value:
        parts.append("-x")
    parts.append(f"-d {_fish_quote(flag.help)}")
    return " ".join(parts)


def fish_script(found: Sequence[Command]) -> str:
    names = _subcommand_names(found)
    lines = [
        "# ipmg completion for fish, generated by `ipmg completion fish`.",
        "# Install it:  ipmg completion fish > ~/.config/fish/completions/ipmg.fish",
        "",
        "complete -c ipmg -f",
    ]
    for command in found:
        if command.name and " " not in command.name:
            lines.append(
                f"complete -c ipmg -n __fish_use_subcommand -a {command.name} "
                f"-d {_fish_quote(command.help)}"
            )
    for command in found:
        condition = _fish_condition(command, names)
        if command.positionals:
            lines.append(
                f"complete -c ipmg -n {_fish_quote(condition)} "
                f"-a {_fish_quote(' '.join(command.positionals))}"
            )
        lines.extend(_fish_flag(flag, condition) for flag in command.flags)
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- PowerShell


def _ps_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _ps_list(values: Sequence[str]) -> str:
    return "@(" + ", ".join(_ps_quote(value) for value in values) + ")"


def powershell_script(found: Sequence[Command]) -> str:
    """Works in Windows PowerShell 5.1 and PowerShell 7."""
    flags = "\n".join(
        f"        {_ps_quote(command.name)} = {_ps_list([name for flag in command.flags for name in flag.names])}"
        for command in found
    )
    choices, takes_value, files, multi = [], [], [], []
    for command in found:
        for flag in command.flags:
            for name in flag.names:
                key = f"{command.name}|{name}"
                if flag.choices:
                    choices.append(f"        {_ps_quote(key)} = {_ps_list(flag.choices)}")
                if flag.files:
                    files.append(key)
                if flag.takes_value:
                    takes_value.append(key)
                if flag.multiple:
                    multi.append(key)
    positionals = "\n".join(
        f"        {_ps_quote(command.name)} = {_ps_list(command.positionals)}"
        for command in found
        if command.positionals
    )
    names = _subcommand_names(found)
    return f"""# ipmg completion for PowerShell, generated by `ipmg completion powershell`.
# Load it from your $PROFILE:  ipmg completion powershell | Out-String | Invoke-Expression

Register-ArgumentCompleter -Native -CommandName ipmg, ipmg.exe -ScriptBlock {{
    param($wordToComplete, $commandAst, $cursorPosition)

    $subcommands = {_ps_list(names)}
    $flags = @{{
{flags}
    }}
    $choices = @{{
{chr(10).join(choices)}
    }}
    $files = {_ps_list(files)}
    $takesValue = {_ps_list(takes_value)}
    $multiple = {_ps_list(multi)}
    $positionals = @{{
{positionals}
    }}

    # The words before the one being completed, without the command itself.
    $words = @()
    foreach ($element in $commandAst.CommandElements | Select-Object -Skip 1) {{
        if ($element.Extent.EndOffset -lt $cursorPosition -or
            ($element.Extent.EndOffset -eq $cursorPosition -and -not $wordToComplete)) {{
            $words += $element.ToString()
        }}
    }}
    $cmd = ''
    if ($words.Count -gt 0 -and $subcommands -contains $words[0]) {{ $cmd = $words[0] }}
    if ($cmd -eq 'history' -and $words.Count -gt 1 -and $words[1] -eq 'prune') {{ $cmd = 'history prune' }}

    # The flag whose value is being typed: the word before, or the last flag
    # if that one takes several values.
    $flag = ''
    if ($words.Count -gt 0 -and $words[-1] -like '-*') {{
        $flag = $words[-1]
    }} else {{
        for ($i = $words.Count - 1; $i -ge 0; $i--) {{
            if ($words[$i] -like '-*') {{
                if ($multiple -contains "$cmd|$($words[$i])") {{ $flag = $words[$i] }}
                break
            }}
        }}
    }}

    $candidates = @()
    if ($flag -and -not ($wordToComplete -like '-*')) {{
        $key = "$cmd|$flag"
        if ($choices.ContainsKey($key)) {{
            $candidates = $choices[$key]
        }} elseif ($files -contains $key -or $takesValue -contains $key) {{
            return  # nothing offered: PowerShell completes file names
        }}
    }}
    if (-not $candidates) {{
        if ($wordToComplete -like '-*') {{
            $candidates = $flags[$cmd]
        }} elseif ($words.Count -eq 0) {{
            $candidates = $subcommands
        }} elseif ($positionals.ContainsKey($cmd)) {{
            $candidates = $positionals[$cmd]
        }}
    }}

    $candidates | Where-Object {{ $_ -like "$wordToComplete*" }} | ForEach-Object {{
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }}
}}
"""


_RENDERERS = {
    "bash": bash_script,
    "zsh": zsh_script,
    "fish": fish_script,
    "powershell": powershell_script,
}


def script(shell: str) -> str:
    """The completion script for ``shell``, one of :data:`SHELLS`."""
    return _RENDERERS[shell](commands())
